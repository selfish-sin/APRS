export type ErrorKey = keyof typeof ERRORS;

/** 被拒的原因 → 能按语言拼的话（toast / 列表里先存下来，显示时再拼）。 */
export function errorSay(e: { message: string; key?: string; params?: Record<string, TextParam> }): Say {
  const entry = e.key ? (ERRORS as Record<string, Text2>)[e.key] : undefined;
  return entry ? { t: entry, p: e.params } : e.message;
}
