function v(
  key: string,
  name: string,
  phase: Phase,
  kind: StageKind,
  hub: boolean,
  grain: Grain,
  unit: Unit,
  tn: number,
  fileCode: string,
  folder: string,
  upstream: string[],
  workload: DefaultWorkload,
  receive: string,
  deliver: string,
  handTo: string,
  note?: string
): StageTemplate {
  return {
    key,
    name,
    phase,
    kind,
    hub,
    grain,
    unit,
    tn,
    per: 1,
    adminSet: true,
    code: null,
    fileCode,
    folder,
    upstream,
    workload,
    receive,
    deliver,
    handTo,
    ...(note ? { note } : {}),
    ...(unit === "cut" ? { unitLabel: "期" } : {}),
  };
}

export const GROUPS: Record<Group, GroupTemplate> = { animation: ANIMATION, video: VIDEO };
export const GROUP_LIST: GroupTemplate[] = [ANIMATION, VIDEO];

export function groupTemplate(group: Group): GroupTemplate {
  return GROUPS[group];
}

export function stageTemplate(group: Group, key: string): StageTemplate | undefined {
  return GROUPS[group]?.stages.find((s) => s.key === key);
}
