/**
 * 流程模板（SPEC §3）：纯数据。开项目时照着它生成「环节」行；管理员能改的工时和系数
 * 存在世界规则 `rules.rates` 里盖在上面（`template.set_rate`）。
 *
 * 每个环节：名字 · 阶段 · 类型（过渡 / 枢纽 / 审核）· 粒度 · 单位 · Tn（每 per 个单位几小时）·
 * 流程代号 · 上游 · 指示器文案（收什么、交什么、交给谁）· 默认工作量从哪来。
 */
import type { Grain, Group, Phase, StageKind, Unit } from "./model";

/** 开项目时任务的默认工作量从哪来（Layout / 原画监督这些枢纽之后还能在派发时改）。 */
export type DefaultWorkload = "one" | "layerSheets" | "cutSheets" | "keySheets" | "cutSeconds" | "projectSeconds";

export interface StageTemplate {
  key: string;
  name: string;
  phase: Phase;
  kind: StageKind;
  hub: boolean;
  grain: Grain;
  unit: Unit;
  tn: number;
  per: number;
  /** 工时由管理员定（这里是个占位数）。 */
  adminSet?: boolean;
  code: string | null;
  fileCode: string;
  folder: string;
  upstream: string[];
  workload: DefaultWorkload;
  receive: string;
  deliver: string;
  handTo: string;
  /** 补一句说明（报到页、环节节点上显示）。 */
  note?: string;
  /** 单位在这个组里叫什么（视频组的「期」）。 */
  unitLabel?: string;
}

export interface GroupTemplate {
  key: Group;
  name: string;
  /** 一「卡」在这个组里叫什么。 */
  cutLabel: string;
  /** 有没有 A / B 层。 */
  hasLayers: boolean;
  /** 还是草案（等用户确认）。 */
  draft: boolean;
  stages: StageTemplate[];
}

