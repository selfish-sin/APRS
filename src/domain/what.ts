/** 「什么」的两种说法：写的是中文就查表，已经是两种说法就照用。 */
export function whatText(what: string | Text2): Text2 {
  if (typeof what !== "string") return what;
  return { zh: what, en: WHAT_EN[what] ?? what };
}
